using OopDesignChecker.Core;
using OopDesignChecker.Rules;

namespace OopDesignChecker.Analysis;

/*
{
  "責務": "公開APIで使用する具体的な解析依存を組み立てます。",
  "フィールド": []
}
*/
internal static class 既定の解析構成
{
    /*
    {
      "責務": "既存の設定読込、規則、C#ローダー、解析実行器を接続します。",
      "処理": ["既存の具体実装を呼び出す関数を、解析ユースケースへ注入します。"],
      "引数": [],
      "戻り値": "既定の依存を使用する解析ユースケースです。"
    }
    */
    public static 解析ユースケース 作る() =>
        new(
            解析入力読み込み器.読み込む,
            規則一覧.既定の規則一覧を作る,
            プロジェクト読み込み器生成器.生成する,
            診断群を生成する
        );

    /*
    {
      "責務": "選択された規則を所有する具体的な解析実行器を生成します。",
      "処理": ["解析実行器へ規則を渡します。", "プロジェクト群とキャンセル通知を渡して解析します。"],
      "引数": {"規則群": "無効規則を除いた規則です。", "プロジェクト群": "ローダーの読込結果です。", "キャンセル通知": "呼び出し元のキャンセル通知です。"},
      "戻り値": "既存エンジンによる集約と整列を終えた診断です。"
    }
    */
    private static IReadOnlyList<DesignDiagnostic> 診断群を生成する(
        IReadOnlyList<I解析規則> 規則群,
        IReadOnlyList<解析対象プロジェクト> プロジェクト群,
        CancellationToken キャンセル通知
    ) => new 解析実行器(規則群).解析する(プロジェクト群, キャンセル通知);
}
