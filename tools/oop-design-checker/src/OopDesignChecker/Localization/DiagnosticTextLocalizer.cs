using OopDesignChecker.Core;

namespace OopDesignChecker.Localization;

public static class DiagnosticTextLocalizer
{
    public static string Title(DesignDiagnostic diagnostic, UserInterfaceLanguage language) =>
        language == UserInterfaceLanguage.English
            ? diagnostic.Rule.Title
            : JapaneseTitle(diagnostic.Rule.Id) ?? diagnostic.Rule.Title;

    public static string Message(DesignDiagnostic diagnostic, UserInterfaceLanguage language) =>
        language == UserInterfaceLanguage.English
            ? diagnostic.Message
            : JapaneseMessage(diagnostic.Rule.Id) ?? diagnostic.Message;

    private static string? JapaneseTitle(string ruleId) =>
        ruleId switch
        {
            "OOP001" => "同じ役割の型に共通の動作がない",
            "OOP002" => "種類ごとの分岐が繰り返されている",
            "OOP003" => "使われていない共通の仕組みがある",
            "OOP101" => "公開範囲が広すぎる",
            "OOP102" => "継承を許可する必要がない可能性がある",
            "OOP103" => "オブジェクトの状態を使わない処理がある",
            "OOP104" => "オブジェクトを作らずに使えるクラスの可能性がある",
            "OOP105" => "複数のオブジェクトで状態を共有している",
            "OOP106" => "内部の値を外から直接変更できる",
            "OOP107" => "検査を通さず値を変更できる",
            "OOP108" => "別のオブジェクトの状態を操作しすぎている",
            "OOP201" => "中心となる処理が大きく複雑である",
            "OOP301" => "継承が型の役割に合っていない可能性がある",
            "OOP302" => "親型で決めた動作の多くが使われていない",
            "OOP303" => "子型が親型の動作を拒んでいる",
            "OOP304" => "継承が深く複雑になっている",
            "OOP305" => "共通の約束があるのに特定の型へ依存している",
            "OOP306" => "置き換え可能なオブジェクトを直接作っている",
            "OOP307" => "継承より別オブジェクトの利用が適切な可能性がある",
            "OOP401" => "1つのクラスに別々の役割がある",
            "OOP402" => "状態を持つ型に処理が少ない",
            "OOP403" => "関係の薄い依存先を抱えている",
            "OOP404" => "別のオブジェクトの中を何段階もたどっている",
            "OOP405" => "値の受け渡しだけを行う型の可能性がある",
            _ => null,
        };

    private static string? JapaneseMessage(string ruleId) =>
        ruleId switch
        {
            "OOP001" =>
                "同じ役割の複数の型で、共通の動作が別々に定義されています。共通の約束としてまとめる必要があるか確認してください。",
            "OOP002" =>
                "種類ごとの分岐が繰り返されています。各種類に処理を持たせて、呼び出し側の分岐を減らせないか確認してください。",
            "OOP003" =>
                "この共通の仕組みを使う箇所が見つかりません。必要な仕組みか、使う側があるか確認してください。",
            "OOP101" =>
                "この型またはメンバーは、実際に使われる範囲より広く公開されています。必要な範囲だけに公開できないか確認してください。",
            "OOP102" =>
                "この型を継承して使う箇所が見つかりません。今後も継承を許可する必要があるか確認してください。",
            "OOP103" =>
                "この処理はオブジェクトごとの状態を使っていません。型に属する共有処理へ変えられるか確認してください。",
            "OOP104" =>
                "このクラスには、個別のオブジェクトとして持つ状態が見つかりません。オブジェクトを作らずに使う形が適切か確認してください。",
            "OOP105" =>
                "変更できる値が複数のオブジェクトで共有されています。どこが値を管理し、いつまで使うのかを確認してください。",
            "OOP106" =>
                "外部から内部の値を直接変更できる状態です。値の変更方法をこのオブジェクト側で管理できないか確認してください。",
            "OOP107" =>
                "値の確認を通さずに変更できるため、正しくない状態になる可能性があります。変更前の確認をこのオブジェクト側で行えるか確認してください。",
            "OOP108" =>
                "別のオブジェクトが、このオブジェクトの値を読み書きしすぎています。値を持つ側に処理を移せないか確認してください。",
            "OOP201" =>
                "中心となる処理が大きく複雑になっています。内容ごとに処理を分けたり、別のオブジェクトに任せたりできないか確認してください。",
            "OOP301" =>
                "この継承は、型の役割を表すより処理を再利用するために使われている可能性があります。親子として自然な関係か確認してください。",
            "OOP302" =>
                "この型では、親型で決められた動作の多くが使われていません。親子として適切な関係か確認してください。",
            "OOP303" =>
                "この型は親型で使えるはずの動作を拒んだり、使えなくしたりしています。親型の代わりに使える関係か確認してください。",
            "OOP304" =>
                "このプロジェクトでは継承が何段階にも重なっています。処理を追いやすくするため、段階を減らせないか確認してください。",
            "OOP305" =>
                "使っている処理は共通の約束で表せますが、呼び出し側は特定の型に依存しています。特定の型を知らずに済む形にできないか確認してください。",
            "OOP306" =>
                "置き換えて使える別のオブジェクトを、このクラスが直接作っています。作る役割をこのクラスが持つ必要があるか確認してください。",
            "OOP307" =>
                "親の処理を再利用するために継承している可能性があります。別のオブジェクトを利用する形の方が関係を表しやすいか確認してください。",
            "OOP401" =>
                "1つのクラスに、別々に管理できる値や処理のまとまりが複数ある可能性があります。別のクラスに分けられないか確認してください。",
            "OOP402" =>
                "値を持つクラス自身には処理が少なく、値を使う処理が別のクラスに集まっている可能性があります。値を持つ側に処理を移せないか確認してください。",
            "OOP403" =>
                "このクラスは、互いに関係の薄い複数の相手に依存している可能性があります。1つの役割にまとまっているか確認してください。",
            "OOP404" =>
                "別のオブジェクトの中を何段階もたどって処理しています。相手の内部構造を知らずに済む形にできないか確認してください。",
            "OOP405" =>
                "このクラスは値の読み書きが中心で、値を使った処理がほとんどありません。値を運ぶだけの役割でなければ、処理を置く場所を確認してください。",
            _ => null,
        };
}
