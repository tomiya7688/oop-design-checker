using OopDesignChecker.Core;

namespace OopDesignChecker.Localization;

public static class DiagnosticTextLocalizer
{
    public static string Title(DesignDiagnostic diagnostic, UserInterfaceLanguage language) =>
        language == UserInterfaceLanguage.English
            ? diagnostic.Rule.Title
            : JapaneseTitle(diagnostic.Rule.Id) ?? diagnostic.Rule.Title;

    public static string Message(DesignDiagnostic diagnostic, UserInterfaceLanguage language) =>
        language == UserInterfaceLanguage.English
            ? diagnostic.Message
            : JapaneseMessage(diagnostic.Rule.Id) ?? diagnostic.Message;

    private static string? JapaneseTitle(string ruleId) =>
        ruleId switch
        {
            "OOP001" => "共通抽象の欠如",
            "OOP002" => "型分岐によるポリモーフィズム回避",
            "OOP003" => "不要な抽象化",
            "OOP101" => "過剰な可視性",
            "OOP102" => "sealed化候補",
            "OOP103" => "staticメンバー候補",
            "OOP104" => "staticクラス候補",
            "OOP105" => "状態を持つstatic設計",
            "OOP106" => "カプセル化の漏れ",
            "OOP107" => "オブジェクト不変条件を迂回可能",
            "OOP108" => "過剰な外部状態操作",
            "OOP201" => "主処理が過大",
            "OOP301" => "不自然な継承関係",
            "OOP302" => "親契約の大半を未使用",
            "OOP303" => "子が親の振る舞いを無効化",
            "OOP304" => "継承階層が深すぎる",
            "OOP305" => "抽象があるのに具象へ依存",
            "OOP306" => "回避可能な具象生成依存",
            "OOP307" => "継承より合成が適切な可能性",
            "OOP401" => "1クラスに複数オブジェクトの可能性",
            "OOP402" => "貧血オブジェクト候補",
            "OOP403" => "無関係な依存が過剰",
            "OOP404" => "オブジェクト内部の過剰なナビゲーション",
            "OOP405" => "getter/setterのみのオブジェクト候補",
            _ => null,
        };

    private static string? JapaneseMessage(string ruleId) =>
        ruleId switch
        {
            "OOP001" =>
                "同じ概念として扱われている複数の型に共通の抽象がありません。共有される振る舞いを表す抽象が必要か確認してください。",
            "OOP002" =>
                "具象型や型コードによる分岐でポリモーフィズムを回避している可能性があります。振る舞いを共通抽象へ移せないか確認してください。",
            "OOP003" =>
                "この抽象は共有概念や拡張点として使われておらず、儀礼的な抽象化になっている可能性があります。",
            "OOP101" =>
                "この型またはメンバーは、実際の利用範囲より広く公開されている可能性があります。必要最小限の可視性を検討してください。",
            "OOP102" =>
                "この型は現在の設計では継承拡張点として使われていません。意図的な拡張点でなければsealed化を検討してください。",
            "OOP103" =>
                "このインスタンスメンバーはオブジェクト状態を利用していません。staticにできる可能性があります。",
            "OOP104" =>
                "このクラスは意味のあるインスタンス状態を持たず、ポリモーフィズムやDI上の理由も見つかりません。staticクラスにできる可能性があります。",
            "OOP105" =>
                "可変なstatic状態が共有されており、グローバル状態として振る舞う可能性があります。所有範囲やライフタイムを明確にしてください。",
            "OOP106" =>
                "内部表現または可変状態が外部へ直接公開されています。所有オブジェクトを経由せず変更できない形にできるか確認してください。",
            "OOP107" =>
                "外部コードがオブジェクトの検証を迂回して状態を変更でき、不変条件を破れる可能性があります。",
            "OOP108" =>
                "別のクラスが対象オブジェクトの状態を直接読み書きしすぎています。状態を所有するオブジェクトへ振る舞いを移せないか確認してください。",
            "OOP201" =>
                "主要な処理が大きく複雑になっています。意味のある処理フェーズや協調オブジェクトへ分解できないか確認してください。",
            "OOP301" =>
                "この継承は親子関係より実装再利用を目的としている可能性があります。意味のあるis-a関係か確認してください。",
            "OOP302" =>
                "子型が親契約の主要部分を実質的に利用または実装していません。継承関係が適切か確認してください。",
            "OOP303" =>
                "子型が親契約で期待される振る舞いを拒否または無効化しています。親型として置換可能か確認してください。",
            "OOP304" =>
                "プロジェクト内の継承階層が深くなっています。振る舞いの追跡が難しくなるため、階層を浅くできないか確認してください。",
            "OOP305" =>
                "利用している振る舞いは抽象で表現できるのに、呼び出し側が具象型へ依存しています。抽象への依存で十分か確認してください。",
            "OOP306" =>
                "置換可能な協調オブジェクトをこのクラスが直接生成しています。生成責務を本当に所有しているか確認してください。",
            "OOP307" =>
                "親実装を再利用するための継承になっている可能性があります。合成で関係を表した方が明確か確認してください。",
            "OOP401" =>
                "1つのクラス内に独立して存在できる状態・振る舞いのまとまりが複数ある可能性があります。別オブジェクトとして成立するか確認してください。",
            "OOP402" =>
                "状態を持つオブジェクト自身に振る舞いが少なく、意味のある処理が外部サービスへ偏っている可能性があります。",
            "OOP403" =>
                "このオブジェクトが互いに無関係な依存グループを多く抱えている可能性があります。1つのオブジェクトとしてまとまっているか確認してください。",
            "OOP404" =>
                "別オブジェクトの内部グラフを深く辿って振る舞いを呼び出しています。内部構造への結合を減らせないか確認してください。",
            "OOP405" =>
                "この型はgetter/setter中心で、意味のある振る舞いがほとんどありません。単なるデータ運搬型でないなら振る舞いの配置を確認してください。",
            _ => null,
        };
}
